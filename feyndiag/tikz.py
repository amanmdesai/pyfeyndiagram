from __future__ import annotations

from .layout import label_side, layout
from .model import LATEX, kind

SCALE = 1.5

_STYLE = {"photon": "photon", "boson": "boson", "gluon": "gluon", "scalar": "scalar"}

_PREAMBLE = r"""\documentclass[a4paper,11pt]{article}
\usepackage[margin=1.5cm]{geometry}
\usepackage{tikz-feynman}
\tikzfeynmanset{compat=1.1.0}
"""


def tikz_picture(lay) -> str:
    """tikz-feynman code for one diagram, using explicit vertex coordinates."""
    rows = [r"\begin{tikzpicture}", r"\begin{feynman}"]
    for node in sorted(lay.pos, key=lambda n: (n[0], int(n[1:]))):
        x, y = lay.pos[node]
        coords = f"at ({x * SCALE:.2f},{y * SCALE:.2f})"
        if node in lay.externals:
            rows.append(rf"\vertex ({node}) {coords} {{${LATEX[lay.externals[node][0]]}$}};")
        else:
            rows.append(rf"\vertex ({node}) {coords};")

    edges = []
    for line in lay.lines:
        style = kind(line.pdg)
        if style == "fermion":
            options = "fermion" if line.pdg > 0 else "anti fermion"
        else:
            options = _STYLE[style]
        if not line.external:
            side = label_side(lay.pos[line.a], lay.pos[line.b])
            key = "edge label" if side > 0 else "edge label'"
            options += rf", {key}=\({LATEX[line.pdg]}\)"
        edges.append(f"({line.a}) -- [{options}] ({line.b})")
    rows.append(r"\diagram* {")
    rows.append(",\n".join("  " + e for e in edges))
    rows.append("};")
    rows += [r"\end{feynman}", r"\end{tikzpicture}"]
    return "\n".join(rows)


def tex_document(results, cols: int = None) -> str:
    """Standalone LaTeX document; each diagram is also a macro \\FeynDiagram{n}."""
    macros = []
    body = []
    counter = 0
    for process, diagrams in results:
        layouts = [layout(d) for d in diagrams]
        height = layouts[0].ymax - layouts[0].ymin + 1.0
        per_row = cols or (2 if height > 3.0 else 3)
        first = counter + 1
        for lay in layouts:
            counter += 1
            macros.append(
                rf"\expandafter\newcommand\csname feyndiagram{counter}\endcsname{{%" + "\n"
                + tikz_picture(lay) + "%\n}"
            )
        body.append(
            rf"\subsection*{{${process.latex()}$ \normalfont({len(diagrams)} diagram"
            + ("s" if len(diagrams) != 1 else "") + ")}"
        )
        numbers = list(range(first, counter + 1))
        for start in range(0, len(numbers), per_row):
            cells = [rf"\FeynCell{{{n}}}" for n in numbers[start:start + per_row]]
            body.append("\\noindent " + r"\hfill ".join(cells) + r"\par\bigskip")

    return (
        "% Generated by feyndiag. Compile with pdflatex (needs the tikz-feynman package).\n"
        "% Copy the preamble lines and the \\FeynDiagram definitions into your own document\n"
        "% to use \\FeynDiagram{n} anywhere.\n"
        + _PREAMBLE
        + r"\newcommand{\FeynDiagram}[1]{\csname feyndiagram#1\endcsname}" + "\n"
        + r"\newcommand{\FeynCell}[1]{\begin{tabular}[t]{@{}c@{}}\FeynDiagram{#1}\\[1ex]"
        + r"\small Diagram~#1\end{tabular}}" + "\n\n"
        + "\n\n".join(macros)
        + "\n\n\\begin{document}\n\\setlength{\\parindent}{0pt}\n"
        + "\n".join(body)
        + "\n\\end{document}\n"
    )
